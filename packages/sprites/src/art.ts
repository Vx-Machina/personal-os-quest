/**
 * Hand-drawn 16x16 pixel art as palette grids (see palette.ts).
 * Grids hold fill colours only; the 1px dark outline is generated (raster.ts).
 * `at(top, rows)` places `rows` starting at row `top` and pads the rest.
 */
export const CELL = 16;

function at(top: number, rows: string[]): string[] {
  const grid = Array.from({ length: CELL }, () => '.'.repeat(CELL));
  rows.forEach((row, i) => {
    grid[top + i] = row;
  });
  return grid;
}

